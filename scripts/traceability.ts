/**
 * Generates docs/requirements-traceability-matrix.md and docs/test-catalog.md
 * from scripts/requirements.ts, the real test inventory (`playwright test --list`)
 * and – when present – the latest results (reports/json/results.json).
 *
 * Fails (exit 1) if a requirement references a test ID that does not exist,
 * so the RTM can never silently drift from the suite.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { NON_PLAYWRIGHT_REQUIREMENTS, REQUIREMENTS } from './requirements';

interface Spec {
  title: string;
  file: string;
  line: number;
  tags: string[];
  tests: { expectedStatus: string; status?: string }[];
}
interface Suite {
  specs: Spec[];
  suites?: Suite[];
}

const root = path.resolve(__dirname, '..');

function collect(suites: Suite[]): Spec[] {
  const out: Spec[] = [];
  const walk = (s: Suite) => {
    out.push(...s.specs);
    s.suites?.forEach(walk);
  };
  suites.forEach(walk);
  return out;
}

const listJson = execFileSync(
  process.platform === 'win32' ? 'npx.cmd' : 'npx',
  ['playwright', 'test', '--list', '--reporter=json'],
  {
    cwd: root,
    encoding: 'utf8',
    shell: process.platform === 'win32',
    maxBuffer: 50 * 1024 * 1024,
  },
);
const inventory = collect((JSON.parse(listJson) as { suites: Suite[] }).suites);

const resultsPath = path.join(root, 'reports', 'json', 'results.json');
const results = existsSync(resultsPath)
  ? collect((JSON.parse(readFileSync(resultsPath, 'utf8')) as { suites: Suite[] }).suites)
  : [];
const outcome = new Map(results.map((s) => [`${s.file}:${s.title}`, s.tests[0]]));

const idOf = (title: string) => title.split(' ')[0]!;
const byId = new Map<string, Spec[]>();
for (const spec of inventory)
  byId.set(idOf(spec.title), [...(byId.get(idOf(spec.title)) ?? []), spec]);

const missing = REQUIREMENTS.flatMap((r) =>
  r.tests.filter((t) => !byId.has(t)).map((t) => `${r.id} → ${t}`),
);
if (missing.length > 0) {
  console.error(`Traceability error – referenced tests not found:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const mapped = new Set(REQUIREMENTS.flatMap((r) => r.tests));
const unmapped = [...byId.keys()].filter((id) => !mapped.has(id));

function statusOf(spec: Spec): 'pass' | 'known-defect' | 'fail' | 'skipped' | 'not-run' {
  const t = outcome.get(`${spec.file}:${spec.title}`);
  if (!t?.status) return 'not-run';
  if (t.status === 'skipped') return 'skipped';
  if (t.status === 'expected') return t.expectedStatus === 'failed' ? 'known-defect' : 'pass';
  return 'fail';
}

const rows = REQUIREMENTS.map((r) => {
  const specs = r.tests.flatMap((t) => byId.get(t) ?? []);
  const statuses = specs.map(statusOf);
  const files = [...new Set(specs.map((s) => `\`tests/${s.file.replace(/\\/g, '/')}\``))];
  const defects = [
    ...new Set(specs.filter((s) => statusOf(s) === 'known-defect').map((s) => idOf(s.title))),
  ];
  const verdict = statuses.includes('fail')
    ? '❌ Failing'
    : statuses.includes('known-defect')
      ? '⚠️ Covered – defect open'
      : statuses.every((s) => s === 'not-run')
        ? '◻️ Covered – not run'
        : '✅ Covered – passing';
  return { r, specs, files, defects, verdict };
});

const rtm = [
  '# Requirements Traceability Matrix',
  '',
  '> Generated by `npm run docs:traceability` from `scripts/requirements.ts`, the live test inventory and the latest results in `reports/json/results.json`. Do not edit by hand.',
  '',
  `Requirements: **${REQUIREMENTS.length + NON_PLAYWRIGHT_REQUIREMENTS.length}** · Automated test cases: **${inventory.length}** · Requirements with ≥ 1 automated test: **${REQUIREMENTS.length}/${REQUIREMENTS.length}** (Playwright) + ${NON_PLAYWRIGHT_REQUIREMENTS.length} verified by other means.`,
  '',
  'Coverage status: ✅ all mapped tests passed in the last run · ⚠️ covered, but at least one mapped test reproduces an open defect · ❌ unexpected failure · ◻️ not executed in the last run.',
  '',
  '| Req. ID | Feature | Requirement | Acceptance criteria | Test cases | Automated test files | Tests | Status | Open defects |',
  '| --- | --- | --- | --- | --- | --- | ---: | --- | --- |',
  ...rows.map(
    ({ r, specs, files, defects, verdict }) =>
      `| ${r.id}${r.inferred ? ' *(inferred)*' : ''} | ${r.feature} | ${r.description} | ${r.acceptance} | ${r.tests.join(', ')} | ${files.join('<br>')} | ${specs.length} | ${verdict} | ${defects.join(', ') || '–'} |`,
  ),
  ...NON_PLAYWRIGHT_REQUIREMENTS.map(
    (r) =>
      `| ${r.id} | ${r.feature} | ${r.description} | – | – | ${r.evidence} | – | see evidence | ${r.id === 'REQ-NFR-04' ? 'BUG-007' : '–'} |`,
  ),
  '',
  '## Requirement sources',
  '',
  ...REQUIREMENTS.map((r) => `- **${r.id}** – ${r.source}`),
  '',
  '## Tests not mapped to a requirement',
  '',
  unmapped.length
    ? unmapped.map((u) => `- ${u}`).join('\n')
    : 'None – every automated test traces to at least one requirement.',
  '',
].join('\n');

const catalog = [
  '# Automated Test Catalog',
  '',
  '> Generated by `npm run docs:traceability` from `playwright test --list`. One row per executable test case (parameterised cases expanded).',
  '',
  '| # | Test ID | Title | File | Tags | Requirement(s) | Last result |',
  '| ---: | --- | --- | --- | --- | --- | --- |',
  ...inventory.map((s, i) => {
    const reqs = REQUIREMENTS.filter((r) => r.tests.includes(idOf(s.title))).map((r) => r.id);
    return `| ${i + 1} | ${idOf(s.title)} | ${s.title.slice(idOf(s.title).length + 1).replace(/\|/g, '\\|')} | \`${s.file.replace(/\\/g, '/')}:${s.line}\` | ${s.tags.map((t) => `\`${t}\``).join(' ')} | ${reqs.join(', ')} | ${statusOf(s)} |`;
  }),
  '',
].join('\n');

writeFileSync(path.join(root, 'docs', 'requirements-traceability-matrix.md'), rtm);
writeFileSync(path.join(root, 'docs', 'test-catalog.md'), catalog);
console.log(
  `RTM: ${REQUIREMENTS.length} requirements, ${inventory.length} tests, ${unmapped.length} unmapped → docs/requirements-traceability-matrix.md, docs/test-catalog.md`,
);
